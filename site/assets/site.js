  const normalizeLocale = (value) => {
    const locale = String(value || "").toLowerCase();
    if (locale === "zh-tw" || locale.startsWith("zh")) return "zh-TW";
    if (locale === "ja" || locale.startsWith("ja-")) return "ja";
    if (locale === "de" || locale.startsWith("de-")) return "de";
    return "en";
  };

  const valueFor = (locale, key, fallback) => translations[locale]?.[key] ?? fallback;

  const updateBrowserLinks = (locale) => {
    document.querySelectorAll('a[href^="https://teddashh.github.io/multi-ai-chat/"]').forEach((link) => {
      const url = new URL("https://teddashh.github.io/multi-ai-chat/");
      if (locale !== "en") url.searchParams.set("lang", locale);
      link.href = url.toString();
    });
  };

  const applyLocale = (locale, announce = false) => {
    document.documentElement.lang = locale;
    textNodes.forEach((node) => {
      const fallback = originalText.get(node) ?? "";
      node.textContent = locale === "en" ? fallback : valueFor(locale, node.dataset.i18n, fallback);
    });
    ariaNodes.forEach((node) => {
      const fallback = originalAria.get(node) ?? "";
      node.setAttribute("aria-label", locale === "en" ? fallback : valueFor(locale, node.dataset.i18nAria, fallback));
    });
    altNodes.forEach((node) => {
      const fallback = originalAlt.get(node) ?? "";
      node.setAttribute("alt", locale === "en" ? fallback : valueFor(locale, node.dataset.i18nAlt, fallback));
    });

    document.title = metadata[locale].title;
    document.querySelector('meta[name="description"]')?.setAttribute("content", metadata[locale].description);
    document.querySelector('meta[property="og:title"]')?.setAttribute("content", metadata[locale].title);
    document.querySelector('meta[property="og:description"]')?.setAttribute("content", metadata[locale].description);
    document.querySelector("#language").value = locale;
    updateBrowserLinks(locale);

    if (announce) {
      const status = document.querySelector("#language-status");
      status.textContent = locale === "en" ? "Website language changed to English" : valueFor(locale, "language.changed", "");
    }
  };

  const params = new URLSearchParams(window.location.search);
  const requestedLocale = params.has("lang")
    ? normalizeLocale(params.get("lang"))
    : normalizeLocale(navigator.languages?.[0] ?? navigator.language);

  applyLocale(requestedLocale);

  document.querySelector("#language").addEventListener("change", (event) => {
    const locale = normalizeLocale(event.target.value);
    const url = new URL(window.location.href);
    url.searchParams.set("lang", locale);
    window.history.replaceState({}, "", url);
    applyLocale(locale, true);
  });

  document.querySelector("#year").textContent = String(new Date().getFullYear());
  document.documentElement.dataset.localeReady = "true";
